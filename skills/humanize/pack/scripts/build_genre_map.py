NORM = {'废土/末世': '废土', '灵异/悬疑': '灵异', '仙侠': '仙侠/玄幻',
        '玄幻': '仙侠/玄幻', '西幻': '西幻/异世界', '都市': '都市/职业'}


def main():
    old = {}
    if os.path.exists(OLD_JSON):
        for it in json.load(io.open(OLD_JSON, encoding='utf-8')):
            old[it['book']] = it.get('genre', '')

    rows = []
    for fn in sorted(os.listdir(CORPUS)):
        if not fn.endswith('.txt'):
            continue
        title = os.path.splitext(fn)[0].rsplit('_', 1)[0]
        if title in MANUAL:                      # 人工判定优先（可覆盖老标签）
            g, src = MANUAL[title], 'manual'
        elif fn in old and old[fn]:              # 老语料沿用已有标签
            g, src = old[fn], 'existing'
        else:                                    # 关键词兜底
            g, src = '未分类', 'auto'
            for pat, gg in KEYWORDS:
                if re.search(pat, title, re.I):
                    g = gg
                    break
        g = NORM.get(g, g)
        rows.append({'book': fn, 'genre': g, 'source': src})

    json.dump(rows, io.open(OUT, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    cnt = Counter(r['genre'] for r in rows)
    print(f'已写 {OUT}  共 {len(rows)} 本')
    for g, c in cnt.most_common():
        print(f'  {g:<12} {c}')
    un = [r['book'] for r in rows if r['genre'] == '未分类']
    if un:
        print(f'\n未分类 {len(un)} 本：')
        for b in un:
            print('  ·', b)


if __name__ == '__main__':
    main()

